#!/usr/bin/env bash
# Split each Source Serif 4 variable font in fonts-src/ into two files in
# static/fonts/: a Latin subset that nearly every page needs, and a file with
# every other character the font covers. It writes assets/css/_fonts.css,
# which declares both with unicode-range, so a browser downloads the second only for a page that uses
# one of its characters (Turkish, Polish, Cyrillic, Greek, maths symbols...).
# Every page still renders in the same font as before.
#
# Why: the full Roman font is 430 KB, and on 2026-11-22 the two fonts were
# 40% of the site's Netlify bandwidth, which is billed in credits. The fonts
# are cached for a year (netlify.toml), so the cost is first visits.
#
# Rerun after replacing a font in fonts-src/, and bump VERSION below (and the
# preload in layouts/partials/head.html): the files are served immutable.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="$REPO_ROOT/fonts-src"
OUT="$REPO_ROOT/static/fonts"
VERSION=v1

# Google Fonts' "latin" range.
LATIN="U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD"

mkdir -p "$OUT"
for style in Roman Italic; do
  font="$SRC/SourceSerif4Variable-$style.ttf.woff2"
  pyftsubset "$font" --unicodes="$LATIN" --layout-features='*' --flavor=woff2 \
    --output-file="$OUT/SourceSerif4-$style-latin-$VERSION.woff2"
  pyftsubset "$font" --unicodes="$(python3 - "$font" "$LATIN" <<'PY'
import sys
from fontTools.ttLib import TTFont
font, latin = sys.argv[1:]
covered = set()
for part in latin.split(","):
    start, _, end = part[2:].partition("-")
    covered |= set(range(int(start, 16), int(end or start, 16) + 1))
rest = sorted(set(TTFont(font).getBestCmap()) - covered)
print(",".join(f"U+{c:04X}" for c in rest))
PY
)" --layout-features='*' --flavor=woff2 \
    --output-file="$OUT/SourceSerif4-$style-rest-$VERSION.woff2"
done
python3 - "$OUT" "$VERSION" "$REPO_ROOT/assets/css/_fonts.css" <<'PY'
import sys
from pathlib import Path
from fontTools.ttLib import TTFont
out, version, css = sys.argv[1:]

def ranges(path):
    cps = sorted(TTFont(path).getBestCmap())
    spans, start, end = [], cps[0], cps[0]
    for c in cps[1:]:
        if c == end + 1:
            end = c
        else:
            spans.append((start, end))
            start = end = c
    spans.append((start, end))
    return ", ".join(f"U+{a:04X}" if a == b else f"U+{a:04X}-{b:04X}" for a, b in spans)

faces = ["/* Generated by scripts/subset-fonts.sh; do not edit. Each unicode-range is\n"
         "   exactly the file's coverage, so a page fetches only the files it needs. */"]
for style, css_style in (("Roman", "normal"), ("Italic", "italic")):
    for part in ("latin", "rest"):
        name = f"SourceSerif4-{style}-{part}-{version}.woff2"
        faces.append(
            "@font-face {\n"
            "  font-family: 'Source Serif 4';\n"
            f"  src: url('/fonts/{name}') format('woff2');\n"
            "  font-weight: 200 900;\n"
            f"  font-style: {css_style};\n"
            "  font-display: swap;\n"
            f"  unicode-range: {ranges(f'{out}/{name}')};\n"
            "}")
Path(css).write_text("\n\n".join(faces) + "\n")
PY
ls -l "$OUT"
