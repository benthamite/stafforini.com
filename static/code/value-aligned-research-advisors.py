    def _latest_completed_us_market_date(requested_date):
        """Use the previous business day while the current US session is open."""
        try:
            now_ny = datetime.now(ZoneInfo('America/New_York'))
        except Exception:
            return requested_date
        if requested_date != now_ny.strftime('%Y-%m-%d'):
            return requested_date
        market_data_cutoff = now_ny.replace(hour=18, minute=0, second=0,
                                            microsecond=0)
        if now_ny >= market_data_cutoff:
            return requested_date
        prev = pd.Timestamp(requested_date) - pd.tseries.offsets.BDay(1)
        return prev.strftime('%Y-%m-%d')


