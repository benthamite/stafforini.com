    def _marketdata_get(path, params, api_key):
        """Fetch a MarketData endpoint, returning normalized row dictionaries.

        Raises on HTTP errors or a non-'ok' status. 'no_data' is returned as
        an empty list so that callers can distinguish 'nothing available' from
        'request failed'.
        """
        headers = {'Accept': 'application/json', 'Authorization': f'Bearer {api_key}'}
        last_error = None
        for attempt in range(1, _MD_MAX_ATTEMPTS + 1):
            try:
                resp = requests.get(_MD_BASE + path, params=params,
                                    headers=headers, timeout=30)
                if resp.status_code != 429:
                    break
                last_error = requests.HTTPError(
                    f"429 Too Many Requests for {_MD_BASE + path}")
                retry_after = resp.headers.get('Retry-After')
                try:
                    delay = float(retry_after) if retry_after else None
                except (TypeError, ValueError):
                    delay = None
                if attempt == _MD_MAX_ATTEMPTS:
                    break
                time.sleep(delay if delay is not None else min(90, 10 * attempt))
            except (requests.exceptions.Timeout,
                    requests.exceptions.ConnectionError) as exc:
                last_error = exc
                if attempt == _MD_MAX_ATTEMPTS:
                    raise
                time.sleep(min(90, 10 * attempt))
        else:
            raise last_error or RuntimeError(f"MarketData request failed: {path}")
        try:
            resp.raise_for_status()
        except requests.exceptions.HTTPError as exc:
            raise RuntimeError(str(exc)) from exc
        body = resp.json()
        status = body.get('s')
        if status == 'no_data':
            return []
        if status != 'ok':
            raise RuntimeError(
                f"MarketData {path} returned status={status!r}: "
                f"{body.get('errmsg') or body}")
        lengths = [len(v) for v in body.values() if isinstance(v, list)]
        n = max(lengths) if lengths else 0
        rows = []
        for i in range(n):
            row = {}
            for key, val in body.items():
                if isinstance(val, list):
                    row[key] = val[i] if i < len(val) else None
                else:
                    row[key] = val
            rows.append(row)
        return rows


